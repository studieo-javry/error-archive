-- =============================================================================
-- V13: Sentry 연동 Phase 1 (Inbound 감지 → Case 후보) 기반 테이블.
--
-- Sentry Issue Alert(신규 이슈 / regression=resolved→unresolved)만 웹훅으로 받아,
-- 받은 편지함(sentry_webhook_inbox)에 즉시 적재 후 비동기 처리 → 워크스페이스에 Case "후보"
-- (sentry_issue_case)를 만든다. 무조건 Case 생성하지 않고 후보로 두며, 사용자가 채택 시 승격한다.
--
-- 설계: docs/design/external-integrations.md, docs/design/phase1-sentry-slack-detail.md
-- 주의(MVP 단순화):
--  - 웹훅 서명은 단일 공유 시크릿(core.sentry.client-secret, 환경변수)으로 검증 → 프로젝트별
--    시크릿을 DB 에 저장하지 않는다(at-rest 암호화 미도입, github 웹훅 시크릿과 같은 방식).
--  - 프로젝트 매핑은 Sentry 프로젝트 slug 기준(org 는 참고용). 멀티-org 충돌은 후속에서 확장.
--  - github_webhook_inbox 와 같은 모양(받은 편지함 패턴). Sentry 엔 delivery id 가 없어 멱등 키는
--    본문 sha256(event_key).
-- =============================================================================

-- 받은 편지함 — 수신 즉시 PENDING INSERT, 처리기가 DONE/SKIPPED, 실패는 backoff 재시도 → FAILED.
CREATE TABLE sentry_webhook_inbox (
    event_key     VARCHAR(64)  PRIMARY KEY,   -- sha256(body) hex — 같은 본문 재전송 멱등
    resource      VARCHAR(40)  NOT NULL,       -- Sentry-Hook-Resource (issue 등)
    action        VARCHAR(40),                 -- payload action (created / unresolved 등)
    payload       JSONB        NOT NULL,        -- 원문(검증 후)
    status        VARCHAR(12)  NOT NULL,        -- PENDING | DONE | SKIPPED | FAILED
    attempts      INTEGER      NOT NULL,
    last_error    TEXT,
    received_at   TIMESTAMPTZ  NOT NULL,
    processed_at  TIMESTAMPTZ,
    next_retry_at TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_sentry_webhook_inbox_pending ON sentry_webhook_inbox (status, next_retry_at);

-- Sentry 프로젝트 ↔ 워크스페이스 연결. 처리 시 payload 의 프로젝트 slug 로 워크스페이스를 해소한다.
CREATE TABLE sentry_project_link (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id    BIGINT       NOT NULL,
    sentry_org      VARCHAR(128),              -- 참고용(매핑은 프로젝트 slug 기준)
    sentry_project  VARCHAR(128) NOT NULL,     -- Sentry 프로젝트 slug
    created_by      BIGINT       NOT NULL,     -- 연결한 사용자(후보 승격 시 소유자 후보)
    created_at      TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_sentry_project UNIQUE (sentry_project)
);

-- Sentry 이슈 ↔ Case 후보/매핑. 신규 이슈 = PROPOSED, 재발 = REOPEN_PROPOSED, 채택 시 case_id 연결.
CREATE TABLE sentry_issue_case (
    sentry_issue_id   VARCHAR(64)  PRIMARY KEY,  -- Sentry issue id
    workspace_id      BIGINT       NOT NULL,
    short_id          VARCHAR(64),
    fingerprint_key   VARCHAR(400) NOT NULL,     -- 정규화 키(type|culprit) — 과거 Solution 매칭용
    title             TEXT         NOT NULL,
    culprit           TEXT,
    issue_type        VARCHAR(200),
    level             VARCHAR(20)  NOT NULL,
    permalink         TEXT,
    status            VARCHAR(20)  NOT NULL,      -- PROPOSED | ACCEPTED | DISMISSED | REOPEN_PROPOSED
    case_id           BIGINT,                     -- 채택/승격 시 연결된 Case
    occurrences       INTEGER      NOT NULL,
    first_seen_at     TIMESTAMPTZ  NOT NULL,
    last_seen_at      TIMESTAMPTZ  NOT NULL
);
CREATE INDEX ix_sentry_issue_case_ws_status ON sentry_issue_case (workspace_id, status);
CREATE INDEX ix_sentry_issue_case_fingerprint ON sentry_issue_case (workspace_id, fingerprint_key);
