-- =============================================================================
-- V13: GitHub 연결(connection) 분리 — 설치 1건을 개인 + 다수 워크스페이스에 동시 연결.
--
--   github_installation          = GitHub 쪽 사실만(계정·상태). 범위/연결자 스코프는 여기서 제거.
--   github_connection            = 설치 ↔ 공간(개인=owner_user_id / 워크스페이스=workspace_id) 바인딩.
--   github_connection_repository = 그 연결에서 "사용 선택"한 레포 부분집합.
--
-- 반영 규칙: "Case 공간에 ACTIVE 연결이 있고 그 연결이 이 repo 를 선택했다" (+ repo·설치 ACTIVE).
-- 설계 전제: GitHub 는 계정당 설치 1건만 허용 → connection 층에서 멀티-공간을 표현.
--
-- ★ 되돌릴 수 없음(forward-only, down 없음): 기존 github_installation 은 rebind() 로 workspace_id 를
--   제자리 덮어써 왔으므로 설치 행엔 "마지막" 바인딩만 남아 있다. 과거 바인딩은 이미 소실돼 복원 불가 —
--   이 이전은 현재 상태(설치당 연결 1건)만 충실히 옮긴다. workspace_id 컬럼은 이전 후 drop 한다.
--
-- 주의: 미머지 Sentry PR(#126)도 V13 을 사용 중. 둘 중 나중에 머지되는 쪽이 번호를 재지정해야 함.
-- =============================================================================

CREATE TABLE github_connection (
    connection_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id      BIGINT       NOT NULL REFERENCES github_installation (installation_id),
    -- 공간: 정확히 하나만 채워진다. 개인=owner_user_id, 워크스페이스=workspace_id.
    owner_user_id        BIGINT,
    workspace_id         BIGINT,
    connected_by_user_id BIGINT       NOT NULL,  -- 감사용(연결을 만든 사람)
    status               VARCHAR(20)  NOT NULL,   -- ACTIVE | DISCONNECTED
    created_at           TIMESTAMP(6) NOT NULL,
    updated_at           TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_github_connection_space CHECK (
        (owner_user_id IS NOT NULL AND workspace_id IS NULL) OR
        (owner_user_id IS NULL     AND workspace_id IS NOT NULL)
    )
);

-- 한 설치는 한 공간에 "ACTIVE 최대 1". DISCONNECTED 는 재연결 위해 누적 허용 → 부분 유니크.
CREATE UNIQUE INDEX uq_github_connection_personal
    ON github_connection (installation_id, owner_user_id)
    WHERE status = 'ACTIVE' AND owner_user_id IS NOT NULL;
CREATE UNIQUE INDEX uq_github_connection_workspace
    ON github_connection (installation_id, workspace_id)
    WHERE status = 'ACTIVE' AND workspace_id IS NOT NULL;

CREATE INDEX ix_github_connection_installation ON github_connection (installation_id);
CREATE INDEX ix_github_connection_owner        ON github_connection (owner_user_id) WHERE owner_user_id IS NOT NULL;
CREATE INDEX ix_github_connection_workspace    ON github_connection (workspace_id)  WHERE workspace_id IS NOT NULL;

CREATE TABLE github_connection_repository (
    connection_id BIGINT       NOT NULL REFERENCES github_connection (connection_id) ON DELETE CASCADE,
    repo_id       BIGINT       NOT NULL REFERENCES github_repository (repo_id),
    selected_at   TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (connection_id, repo_id)
);
CREATE INDEX ix_github_connection_repository_repo ON github_connection_repository (repo_id);

-- ── 데이터 이전(DROP COLUMN 전에 실행 — workspace_id 를 읽어야 함) ──
-- 기존 설치 1건 → ACTIVE 연결 1건. workspace_id 로 공간을 정한다(NULL=개인, 소유자=installed_by_user_id).
INSERT INTO github_connection
    (installation_id, owner_user_id, workspace_id, connected_by_user_id, status, created_at, updated_at)
SELECT i.installation_id,
       CASE WHEN i.workspace_id IS NULL THEN i.installed_by_user_id END,
       i.workspace_id,
       i.installed_by_user_id,
       'ACTIVE',
       i.created_at, i.updated_at
FROM github_installation i;

-- 그 연결의 선택 레포 = 현재 활성(removed_at IS NULL) 레포 전부 — 오늘의 "모든 grant = 사용" 동작 보존.
INSERT INTO github_connection_repository (connection_id, repo_id, selected_at)
SELECT c.connection_id, r.repo_id, now()
FROM github_connection c
JOIN github_repository r
  ON r.installation_id = c.installation_id AND r.removed_at IS NULL;

ALTER TABLE github_installation DROP COLUMN workspace_id;
DROP INDEX IF EXISTS ix_github_installation_workspace;
