-- Agent Capture (P0) PR2 — 자동 수집 초안 저장(Capture/Attempt/Solution/Session) + 요청 멱등 영수증.
--
-- 기존 ErrorCase 와 분리된 별도 구조. ErrorCase.status 에 DRAFT 를 추가하지 않는다(미검토 기록이
-- 기존 알림·검색·통계에 섞이지 않게). 검토 반영(import)으로만 Case·Step·Solution 이 된다(PR4).
--
-- 구조화 서사 필드는 직렬화 JSON 을 jsonb 컬럼 하나에 담는다(outbox payload 와 동일 패턴).
-- 엔티티 AgentCaptureEntities.kt 와 정확히 일치해야 한다(Testcontainers ddl-auto=validate).
--
-- ⚠️ origin/alpha 기준 다음 free 번호는 V19 (최신 V18). 미머지 PR(feat/github-user-token-refresh)이
--    V19 를 선점한 상태라, 그 PR 이 먼저 머지되면 이 파일을 V20 으로 올릴 것.

CREATE TABLE agent_capture (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_uuid              UUID         NOT NULL,
    owner_user_id             BIGINT       NOT NULL,
    originating_connection_id UUID         NOT NULL,
    status                    VARCHAR(20)  NOT NULL,
    revision                  INTEGER      NOT NULL,
    title                     VARCHAR(300),
    project                   VARCHAR(200),
    content                   JSONB        NOT NULL,
    created_at                TIMESTAMP(6) NOT NULL,
    updated_at                TIMESTAMP(6) NOT NULL,
    completed_at              TIMESTAMP(6),
    CONSTRAINT uq_agent_capture_uuid UNIQUE (capture_uuid)
);
CREATE INDEX ix_agent_capture_owner_status ON agent_capture (owner_user_id, status);

CREATE TABLE capture_attempt (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id        BIGINT       NOT NULL,
    client_attempt_id VARCHAR(200) NOT NULL,
    order_index       INTEGER      NOT NULL,
    result            VARCHAR(20)  NOT NULL,
    attempt_type      VARCHAR(100),
    detail            JSONB        NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_capture_attempt_client_id UNIQUE (capture_id, client_attempt_id)
);
CREATE INDEX ix_capture_attempt_capture ON capture_attempt (capture_id);

CREATE TABLE capture_solution_candidate (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id         BIGINT       NOT NULL,
    client_solution_id VARCHAR(200) NOT NULL,
    title              VARCHAR(300) NOT NULL,
    content            JSONB        NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_capture_solution_client_id UNIQUE (capture_id, client_solution_id)
);
CREATE INDEX ix_capture_solution_capture ON capture_solution_candidate (capture_id);

CREATE TABLE capture_session (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_uuid      UUID         NOT NULL,
    connection_id     UUID         NOT NULL,
    client_kind       VARCHAR(50)  NOT NULL,
    client_version    VARCHAR(50),
    client_session_id VARCHAR(200) NOT NULL,
    started_at        TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_capture_session_uuid UNIQUE (session_uuid)
);

CREATE TABLE capture_session_link (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    capture_id BIGINT NOT NULL,
    CONSTRAINT uq_capture_session_link UNIQUE (session_id, capture_id)
);
CREATE INDEX ix_capture_session_link_capture ON capture_session_link (capture_id);

CREATE TABLE agent_idempotency_receipt (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_key       VARCHAR(200) NOT NULL,
    operation       VARCHAR(60)  NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,
    response_status INTEGER      NOT NULL,
    response_body   JSONB        NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_agent_idempotency UNIQUE (scope_key, operation, idempotency_key)
);
