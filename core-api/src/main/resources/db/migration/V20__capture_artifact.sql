-- Agent Capture (P0) PR3 — Capture 근거 첨부.
--
-- 기존 스토리지 포트(S3)는 재사용하되, 기존 error_case_attachment 와는 **별도 테이블**로 둔다.
-- (기존 고아 GC 가 error_case_id IS NULL 대상이라, capture 참조 파일을 지우지 않게 격리.)
--
-- 멱등: (capture_id, client_artifact_id) UNIQUE. 같은 clientArtifactId·같은 sha256 = 같은 첨부,
--       다른 sha256 = 409. 엔티티 CaptureArtifactEntity 와 정합(validate).

CREATE TABLE capture_artifact (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id         BIGINT       NOT NULL,
    client_artifact_id VARCHAR(200) NOT NULL,
    object_key         VARCHAR(300) NOT NULL,
    sha256             VARCHAR(64)  NOT NULL,
    content_type       VARCHAR(100) NOT NULL,
    size_bytes         BIGINT       NOT NULL,
    file_name          VARCHAR(300),
    uploader_user_id   BIGINT       NOT NULL,
    status             VARCHAR(20)  NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_capture_artifact_client_id UNIQUE (capture_id, client_artifact_id)
);
CREATE INDEX ix_capture_artifact_capture ON capture_artifact (capture_id);
