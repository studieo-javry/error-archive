-- Agent Capture (P0) — agent 연결 토큰 저장.
--
-- 로컬 커넥터(Claude Code MCP)가 /api/v1/agent/** 호출 시 제시하는 opaque 토큰의 서버측 기록.
-- refresh token(iam_refresh_token)과 같은 해시-저장 패턴: 원문 미저장, sha256 해시만 저장·조회.
-- 폐기는 삭제가 아닌 revoked_at 스탬프(감사 보존). 유효성(폐기/만료)은 매 요청 introspection 에서 검사.
--
-- scopes 는 CSV 단일 컬럼(소수 고정 집합: case:read, capture:read, capture:write, artifact:write).
-- 엔티티 AgentConnectionEntity 와 정확히 일치해야 한다(stg/prod ddl-auto=validate).

CREATE TABLE iam_agent_connection (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT       NOT NULL,
    connection_id UUID         NOT NULL,
    token_hash    VARCHAR(128) NOT NULL,
    scopes        VARCHAR(255) NOT NULL,
    label         VARCHAR(120),
    expires_at    TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    revoked_at    TIMESTAMPTZ,
    last_used_at  TIMESTAMPTZ,
    CONSTRAINT uq_iam_agent_connection_token_hash UNIQUE (token_hash),
    CONSTRAINT uq_iam_agent_connection_connection_id UNIQUE (connection_id)
);

CREATE INDEX ix_iam_agent_connection_owner ON iam_agent_connection (owner_user_id);
