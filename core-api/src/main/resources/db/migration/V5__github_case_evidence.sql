-- =============================================================================
-- V5: GitHub 연동 P1 — Issue/PR 스냅샷, PR↔Issue 장부, Case 연결, 근거 타임라인.
-- 식별은 (repo_id, number). repo_id 는 GitHub 불변 id(github_repository 와 같은 키).
-- 스냅샷·장부는 Case 와 무관(Case 삭제 시 유지), 연결·이벤트는 Case 삭제 시 앱에서 정리(purgeCascade).
-- =============================================================================

-- Issue 스냅샷 — Case 에 연결된 적 있는 Issue 만.
CREATE TABLE github_issue (
    repo_id           BIGINT       NOT NULL,
    number            INTEGER      NOT NULL,
    title             VARCHAR(300) NOT NULL,
    url               VARCHAR(500) NOT NULL,
    state             VARCHAR(10)  NOT NULL,     -- OPEN | CLOSED
    author_login      VARCHAR(100),
    created_at_gh     TIMESTAMPTZ  NOT NULL,
    closed_at_gh      TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ  NOT NULL,     -- 이보다 오래된 정보로 덮어쓰지 않음
    deleted           BOOLEAN      NOT NULL DEFAULT FALSE,
    PRIMARY KEY (repo_id, number)
);

-- PR 스냅샷 + 최신 head 커밋의 CI 요약.
CREATE TABLE github_pull_request (
    repo_id           BIGINT       NOT NULL,
    number            INTEGER      NOT NULL,
    title             VARCHAR(300) NOT NULL,
    url               VARCHAR(500) NOT NULL,
    state             VARCHAR(10)  NOT NULL,     -- OPEN | CLOSED | MERGED
    is_draft          BOOLEAN      NOT NULL DEFAULT FALSE,
    author_login      VARCHAR(100),
    head_sha          VARCHAR(40)  NOT NULL,
    base_ref          VARCHAR(200),
    additions         INTEGER,
    deletions         INTEGER,
    changed_files     INTEGER,
    created_at_gh     TIMESTAMPTZ  NOT NULL,
    merged_at_gh      TIMESTAMPTZ,
    closed_at_gh      TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ  NOT NULL,
    ci_head_sha       VARCHAR(40),               -- head_sha 와 다르면 "새 커밋 CI 대기 중"
    ci_conclusion     VARCHAR(20),               -- SUCCESS | FAILURE | PENDING
    ci_total          INTEGER,
    ci_passed         INTEGER,
    ci_failed_names   JSONB,                     -- ["integration-test", ...] (최대 10개)
    ci_completed_at   TIMESTAMPTZ,
    PRIMARY KEY (repo_id, number)
);
CREATE INDEX ix_github_pr_head ON github_pull_request (repo_id, head_sha);

-- PR↔Issue 장부 — "이 PR 은 이 Issue 를 닫는다". Case 와 무관.
CREATE TABLE github_pr_issue_ref (
    pr_repo_id    BIGINT      NOT NULL,
    pr_number     INTEGER     NOT NULL,
    issue_repo_id BIGINT      NOT NULL,
    issue_number  INTEGER     NOT NULL,
    source        VARCHAR(10) NOT NULL,          -- GITHUB(closingIssuesReferences) | KEYWORD(비기본 브랜치 PR 의 닫는 키워드)
    observed_at   TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (pr_repo_id, pr_number, issue_repo_id, issue_number)
);
CREATE INDEX ix_github_pr_issue_ref_issue ON github_pr_issue_ref (issue_repo_id, issue_number);

-- Case ↔ Issue/PR 연결. 떼기는 detached_at 표시(행을 남겨 자동 재부착 방지).
CREATE TABLE case_github_link (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id             BIGINT      NOT NULL,
    kind                VARCHAR(20) NOT NULL,    -- ISSUE | PULL_REQUEST
    repo_id             BIGINT      NOT NULL,
    number              INTEGER     NOT NULL,
    link_source         VARCHAR(20) NOT NULL,    -- MANUAL | IMPORTED | VIA_ISSUE
    via_issue_repo_id   BIGINT,
    via_issue_number    INTEGER,
    linked_by_user_id   BIGINT,                  -- 자동 부착이면 NULL
    linked_at           TIMESTAMPTZ NOT NULL,
    detached_at         TIMESTAMPTZ,
    detached_by_user_id BIGINT,
    CONSTRAINT uq_case_github_link UNIQUE (case_id, kind, repo_id, number)
);
CREATE INDEX ix_case_github_link_target ON case_github_link (kind, repo_id, number);

-- Case 근거 타임라인. dedupe_key 로 같은 사건 중복 기록 방지(CI 는 같은 키를 최신 집계로 갱신).
CREATE TABLE case_github_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id     BIGINT       NOT NULL,
    type        VARCHAR(30)  NOT NULL,
    kind        VARCHAR(20)  NOT NULL,           -- 관련 대상 종류 ISSUE | PULL_REQUEST
    repo_id     BIGINT       NOT NULL,
    number      INTEGER      NOT NULL,
    occurred_at TIMESTAMPTZ  NOT NULL,           -- GitHub 쪽 발생 시각
    data        JSONB,
    dedupe_key  VARCHAR(160) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_case_github_event UNIQUE (case_id, dedupe_key)
);
CREATE INDEX ix_case_github_event_case ON case_github_event (case_id, occurred_at);
