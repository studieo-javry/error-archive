-- P1(#145) Hook 자동수집 인박스. 커넥터(로컬 큐)가 정규화한 CaptureEvent 를 배치로 전송해 적재한다.
-- 적재(ACCEPTED)는 "영속 저장"일 뿐 Step 구조화가 아니다. 미분류(capture_id NULL)로 보관하다
-- 개발 AI 가 MCP 로 Capture 에 연결(후속 증분)하면 capture_id·status 가 채워진다.
CREATE TABLE capture_event (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id      UUID         NOT NULL,
    owner_user_id      BIGINT       NOT NULL,
    project_binding_id BIGINT,
    client_event_id    VARCHAR(200) NOT NULL,   -- 최초 로컬 저장 시 1회 생성, 재전송에서 유지
    client_kind        VARCHAR(60),
    client_version     VARCHAR(60),
    session_id         VARCHAR(200),            -- clientSessionId
    stream_id          VARCHAR(200),            -- streamId/agentId (제공 시)
    tool_call_id       VARCHAR(200),
    event_type         VARCHAR(60)  NOT NULL,
    local_sequence     BIGINT       NOT NULL,   -- 세션/스트림 범위 순서(전역 순서 아님)
    observed_at        TIMESTAMP(6) NOT NULL,   -- 클라이언트 관측 시각
    received_at        TIMESTAMP(6) NOT NULL,   -- 서버 수신 시각(구분)
    redacted_payload   JSONB        NOT NULL,   -- 마스킹된 payload(≤64KiB). 더 큰 근거는 첨부로
    truncated          BOOLEAN      NOT NULL DEFAULT FALSE,
    evidence_refs      JSONB        NOT NULL,   -- clientArtifactId 참조 배열
    payload_hash       VARCHAR(64)  NOT NULL,   -- 같은 client_event_id 에 다른 payload 충돌 판정
    capture_id         BIGINT,                  -- 연결된 Capture. NULL=UNCLASSIFIED
    status             VARCHAR(20)  NOT NULL,   -- UNCLASSIFIED | LINKED | DISCARDED
    CONSTRAINT uq_capture_event_client_id UNIQUE (connection_id, client_event_id)
);
CREATE INDEX ix_capture_event_owner_status ON capture_event (owner_user_id, status);
CREATE INDEX ix_capture_event_capture ON capture_event (capture_id);
CREATE INDEX ix_capture_event_received ON capture_event (received_at);
