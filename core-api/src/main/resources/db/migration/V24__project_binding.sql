-- P1 토대(이슈 #144 §2 ProjectBinding / #145 "승인된 프로젝트"). 로컬 경로↔프로젝트↔repo 매핑의 정규 단위.
-- P0 의 free-text agent_capture.project 는 하위호환으로 유지하고, project_binding_id 를 nullable 로 추가(점진 이전).
CREATE TABLE project_binding (
    project_binding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id      BIGINT       NOT NULL,
    project_key        VARCHAR(200) NOT NULL,     -- 사용자가 정한 프로젝트 식별자(로컬 경로와는 커넥터가 매핑)
    normalized_repo_id VARCHAR(300),              -- 정규화한 repo 식별자(GitHub 연결 시). 없으면 null
    storage_policy     VARCHAR(30)  NOT NULL DEFAULT 'DEFAULT',
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_project_binding_owner_key UNIQUE (owner_user_id, project_key)
);
CREATE INDEX ix_project_binding_owner ON project_binding (owner_user_id);

-- 세션·초안을 바인딩에 연결(nullable — 기존 행·미바인딩 흐름 하위호환).
ALTER TABLE agent_capture  ADD COLUMN project_binding_id BIGINT REFERENCES project_binding (project_binding_id);
ALTER TABLE capture_session ADD COLUMN project_binding_id BIGINT REFERENCES project_binding (project_binding_id);
