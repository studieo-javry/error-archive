-- 검토 반영(import) 기록. 한 Capture 당 최대 1건(capture_id UNIQUE) — 재반영 멱등·충돌 판정의 기준.
-- request_hash: 정규화한 반영 요청(reviewedRevision + 선택 항목 + markResolved)의 해시.
--   같은 해시 재반영 → 같은 케이스(멱등), 다른 해시 재반영 → 409 CAPTURE_ALREADY_IMPORTED.
-- attempt_step_map: clientAttemptId → 생성된 stepId 매핑(출처 보존).
CREATE TABLE capture_import (
    capture_import_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capture_id        BIGINT       NOT NULL UNIQUE REFERENCES agent_capture (id),
    reviewed_revision INTEGER      NOT NULL,
    reviewer_user_id  BIGINT       NOT NULL,
    reviewed_at       TIMESTAMP(6) NOT NULL,
    target_case_id    BIGINT       NOT NULL,
    request_hash      VARCHAR(64)  NOT NULL,
    attempt_step_map  JSONB        NOT NULL,
    created_at        TIMESTAMP(6) NOT NULL
);
