-- 수집 근거 Case 반영(연결된 수집 근거의 선택적 Import, PR-2). 사용자가 검토에서 선택한, Capture 에 연결된
-- Hook 이벤트(CaptureEvent)를 ErrorCase 의 **독립 스냅샷**으로 영속화한다. CaptureArtifact→CaseAttachment 승격과
-- 같은 "원본 보존 + 반영 시점 스냅샷" 패턴.
--
-- 설계:
--  - source_capture_event_id 는 출처 추적용(FK 아님) — 원본 capture_event 가 GC 돼도 Case 근거는 보존(생명주기 분리).
--  - error_case 에도 FK 없음(error_case_attachment 가문과 동일) — 삭제 정리는 애플리케이션 cascade(DeleteErrorCaseUseCase).
--  - redacted_payload 는 커넥터 마스킹 완료분의 jsonb 스냅샷. visibility_policy 는 노출 정책(현재 소유자 전용 고정).
--  - UNIQUE(error_case_id, source_capture_event_id): 같은 이벤트를 같은 Case 에 중복 스냅샷하지 않는다(재반영 방어).
-- forward-only(down 없음). 인덱스는 엔티티 @Table 에도 선언 — ddl-auto=validate 는 컬럼/타입만 검사.
CREATE TABLE case_event_evidence (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    error_case_id           BIGINT       NOT NULL,
    source_capture_event_id BIGINT       NOT NULL,   -- 원본 capture_event.id (출처 추적, FK 아님)
    source_client_event_id  VARCHAR(200) NOT NULL,
    event_type              VARCHAR(60)  NOT NULL,
    observed_at             TIMESTAMP(6) NOT NULL,    -- 클라이언트 관측 시각
    received_at             TIMESTAMP(6) NOT NULL,    -- 서버 수신 시각
    redacted_payload        JSONB        NOT NULL,    -- 마스킹된 payload 스냅샷
    truncated               BOOLEAN      NOT NULL DEFAULT FALSE,
    reviewed_by_user_id     BIGINT       NOT NULL,
    reviewed_at             TIMESTAMP(6) NOT NULL,
    visibility_policy       VARCHAR(20)  NOT NULL DEFAULT 'OWNER_ONLY',
    CONSTRAINT uq_case_event_evidence UNIQUE (error_case_id, source_capture_event_id)
);
CREATE INDEX ix_case_event_evidence_case ON case_event_evidence (error_case_id);
